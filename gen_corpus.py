# 语气 / 前缀后缀修饰
PREFIXES = ["", "", "", "那个，", "嗯……", "话说，", "对了，", "顺便问一下，"]
SUFFIXES = ["", "", "", "呢？", "啊？", "呀？", "吧？"]


def expand_questions(q):
    """对同一个问题生成多种问法"""
    forms = {q}
    if q in ASK_REWRITES:
        forms.update(ASK_REWRITES[q])
    # 加语气词
    out = set(forms)
    for base in list(forms):
        if len(base) <= 8:
            for p in ["那个，", "嗯，", "话说，"]:
                out.add(p + base)
            for s in ["呢", "啊", "呀"]:
                if not base.endswith(("？", "?", "!", "！")):
                    out.add(base + s)
    return sorted(out)


def build_corpus():
    pairs = []  # (user, assistant)

    # 1. 手写种子
    for q, a in SEED_QA:
        pairs.append((q, a))

    # 2. 问法扩充 (答案不变, 让模型学会对同一意图给出稳定回答)
    for q, a in SEED_QA:
        for variant in expand_questions(q):
            if variant != q:
                pairs.append((variant, a))

