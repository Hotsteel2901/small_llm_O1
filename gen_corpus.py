def main():
    pairs, g_in, g_out, topic_qa, c_in, c_out = build_corpus()

    # 主题多样性: 用同义前缀再扩一轮
    extra = []
    for q, a in SEED_QA:
        for pre in PREFIXES:
            if pre and not q.startswith(("谢谢", "再见", "晚安", "早上好", "晚上好")):
                extra.append((pre + q, a))
    pairs.extend(extra)

    print(f"问答对总数: {len(pairs)}")

    # 单轮样本
    samples = []
    for q, a in pairs:
        samples.append([
            {"role": "user", "content": q},
            {"role": "assistant", "content": a},
        ])

    # 多轮样本
    multi = make_multiturn(4000, topic_qa, g_in, g_out, c_in, c_out)
    samples.extend(multi)

    random.shuffle(samples)
    # 去重
    seen, uniq = set(), []
    for s in samples:
        key = json.dumps(s, ensure_ascii=False)
        if key not in seen:
            seen.add(key)
            uniq.append(s)

    out_path = OUT_DIR / "corpus.jsonl"
    with out_path.open("w", encoding="utf-8") as f:
        for s in uniq:
            f.write(json.dumps({"messages": s}, ensure_ascii=False) + "\n")

    total_turns = sum(len(s) for s in uniq)
    total_chars = sum(len(m["content"]) for s in uniq for m in s)
    print(f"去重后会话数: {len(uniq)}")
    print(f"总消息数: {total_turns}")
    print(f"总字符数: {total_chars}")
    print(f"输出: {out_path}")


if __name__ == "__main__":
    main()
